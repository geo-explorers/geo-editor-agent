#!/usr/bin/env node
// gen-skill-stubs.mjs — make the toolkit's skills discoverable by Claude Code.
//
// WHY: the toolkit keeps its skills at skills/<actionable|non-actionable>/<name>/, which is
// the upstream (content-management) layout and NOT a location any agent scans. Claude Code
// only auto-loads .claude/skills/<name>/SKILL.md. Copying every skill there would create a
// second copy that drifts; instead this writes a thin stub per skill — the real frontmatter
// (so the description triggers correctly) plus a body that routes to the canonical file.
//
// Stubs are generated, deterministic and committed. Re-run after syncing upstream.
//
// Usage:  node tools/gen-skill-stubs.mjs [--check]
//   --check   exit 1 if any stub is missing or stale instead of writing
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const TIERS = ['actionable', 'non-actionable'];
const OUT = '.claude/skills';
const CHECK = process.argv.includes('--check');

function frontmatter(src) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(src);
  if (!m) return null;
  const fm = m[1];
  const name = (/^name:\s*(.+)$/m.exec(fm) || [])[1]?.trim();
  // description may be a folded scalar (">") spanning lines, or a single line
  const dm = /^description:\s*(>-?\s*)?\r?\n?([\s\S]*?)(?=\r?\n[a-zA-Z_-]+:|\r?\n?$)/m.exec(fm);
  let description = dm ? dm[2] : '';
  description = description.split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join(' ').trim();
  const version = (/^\s*version:\s*"?([0-9][^"\s]*)"?/m.exec(fm) || [])[1] || '';
  return { name, description, version };
}

let stale = 0, made = 0;
for (const tier of TIERS) {
  const base = join('skills', tier);
  if (!existsSync(base)) continue;
  for (const dir of readdirSync(base)) {
    const skillMd = join(base, dir, 'SKILL.md');
    if (!existsSync(skillMd)) continue;
    const fm = frontmatter(readFileSync(skillMd, 'utf8'));
    if (!fm?.name || !fm.description) { console.error(`  ! ${skillMd}: cannot read name/description — skipped`); continue; }
    if (fm.name !== dir) console.error(`  ! ${skillMd}: name "${fm.name}" != directory "${dir}" — stub uses the name`);
    const rel = `${base}/${dir}/SKILL.md`.replace(/\\/g, '/');
    const stub = `---
name: ${fm.name}
description: ${fm.description}
metadata:
  version: "${fm.version}"
  stub-for: ${rel}
  tier: ${tier}
---

# ${fm.name} — routed skill

This is a discovery stub. The skill itself lives in the toolkit at
\`${rel}\` (upstream layout, kept intact so it can be synced from content-management).

**Read that file now and follow it exactly.** It is the contract — it carries hard rules,
gates and the scripts' real paths, none of which are repeated here.

Run its scripts from the **repository root** (\`.env\`, \`src/\` and \`skills/\` resolve from there).
${tier === 'actionable' ? '\nThis skill can **write to Geo**. Every write goes through its own dry-run → explicit confirmation gate. Never bypass it.\n' : '\nThis skill is **read-only on Geo**.\n'}
Regenerated by \`tools/gen-skill-stubs.mjs\` — do not edit by hand.
`;
    const outDir = join(OUT, fm.name);
    const outFile = join(outDir, 'SKILL.md');
    const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
    // Compare line-ending-insensitively: a Windows checkout with autocrlf gives CRLF, the
    // generator writes LF, and the manifest tooling already treats those as identical.
    if (current !== null && current.replace(/\r\n/g, '\n') === stub) continue;
    if (CHECK) { stale++; console.log(`  stale: ${outFile}`); continue; }
    mkdirSync(outDir, { recursive: true });
    writeFileSync(outFile, stub);
    made++;
    console.log(`  ${current === null ? 'created' : 'updated'} ${outFile}  (${fm.version})`);
  }
}
if (CHECK) { console.log(stale ? `${stale} stub(s) stale — run tools/gen-skill-stubs.mjs` : 'all stubs current'); process.exit(stale ? 1 : 0); }
console.log(made ? `${made} stub(s) written` : 'all stubs already current');
